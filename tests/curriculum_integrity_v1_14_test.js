const fs=require('fs'),assert=require('assert'),path=require('path');
const root=path.join(__dirname,'..');
const report=JSON.parse(fs.readFileSync(path.join(root,'web/data/curriculum-integrity-audit-2026-2027.json'),'utf8'));
